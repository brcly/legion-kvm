//! Input from this VM's virtual keyboard, tablet and mouse.
use anyhow::{Context, Result, ensure};
use legion_display_channel::input_events::{Batch, Event, TimedEvent};
use std::{
    fs::{self, File, OpenOptions},
    io::{self, Read},
    os::{
        fd::AsRawFd,
        unix::fs::{FileTypeExt, OpenOptionsExt},
    },
    path::Path,
};

#[derive(Clone, Copy)]
struct Axis {
    value: i32,
    min: i32,
    max: i32,
}
impl Axis {
    fn normalized(self) -> f64 {
        ((i64::from(self.value) - i64::from(self.min)) as f64
            / (i64::from(self.max) - i64::from(self.min)) as f64)
            .clamp(0.0, 1.0)
    }
}

fn axis(file: &File, code: u8) -> Result<Option<Axis>> {
    let request = rustix::ioctl::opcode::read::<[i32; 6]>(b'E', 0x40 + code);
    let mut info = [0_i32; 6];
    // SAFETY: the evdev EVIOCGABS request writes one initialized input_absinfo
    // (six i32 fields), into this live array for the duration of the ioctl.
    if unsafe { libc::ioctl(file.as_raw_fd(), request as _, info.as_mut_ptr()) } < 0 {
        let error = io::Error::last_os_error();
        if matches!(error.raw_os_error(), Some(libc::EINVAL | libc::ENOTTY)) {
            return Ok(None);
        }
        return Err(error).context("query virtual input axis");
    }
    Ok((info[2] > info[1]).then_some(Axis {
        value: info[0],
        min: info[1],
        max: info[2],
    }))
}

fn relative_axes(file: &File) -> Result<bool> {
    let request = rustix::ioctl::opcode::read::<[u8; 8]>(b'E', 0x22);
    let mut bits = [0_u8; 8];
    // SAFETY: EVIOCGBIT(EV_REL, 8) writes at most this live eight-byte bitmap.
    if unsafe { libc::ioctl(file.as_raw_fd(), request as _, bits.as_mut_ptr()) } < 0 {
        let error = io::Error::last_os_error();
        if matches!(error.raw_os_error(), Some(libc::EINVAL | libc::ENOTTY)) {
            return Ok(false);
        }
        return Err(error).context("query virtual relative axes");
    }
    Ok(bits[0] & 3 == 3)
}

#[derive(Default)]
struct Decoder {
    absolute: Option<[Axis; 2]>,
    relative_supported: bool,
    relative: [i64; 2],
    dirty: bool,
    dropped: bool,
}
impl Decoder {
    fn flush(&mut self, events: &mut Vec<Event>) {
        if self.dirty
            && let Some([x, y]) = self.absolute
        {
            events.push(Event::Absolute {
                x: x.normalized(),
                y: y.normalized(),
            });
        }
        self.dirty = false;
        if self.relative != [0, 0] {
            let [dx, dy] = self.relative.map(|value| value as f64);
            events.push(Event::Relative {
                dx,
                dy,
                raw_dx: dx,
                raw_dy: dy,
            });
            self.relative = [0, 0];
        }
    }
    fn event(&mut self, kind: u16, code: u16, value: i32, events: &mut Vec<Event>) {
        if kind == 0 && code == 3 {
            // SYN_DROPPED: do not retain stuck keys.
            events.push(Event::Reset);
            self.dirty = false;
            self.relative = [0, 0];
            self.dropped = true;
            return;
        }
        if self.dropped {
            if kind == 0 && code == 0 {
                self.dropped = false;
            }
            return;
        }
        match (kind, code) {
            (0, 0) => self.flush(events),
            (3, 0..=1) => {
                if let Some(axes) = &mut self.absolute {
                    axes[usize::from(code)].value = value;
                    self.dirty = true;
                }
            }
            (2, 0..=1) if self.relative_supported => {
                let axis = &mut self.relative[usize::from(code)];
                *axis = axis.saturating_add(i64::from(value));
            }
            (1, _) if value == 0 || value == 1 => {
                self.flush(events);
                events.push(if (0x110..=0x117).contains(&code) {
                    Event::Button {
                        code: u32::from(code),
                        down: value == 1,
                    }
                } else {
                    Event::Key {
                        code: u32::from(code),
                        down: value == 1,
                    }
                });
            }
            (2, 6 | 8) => {
                self.flush(events);
                events.push(Event::Axis {
                    axis: u32::from(code == 6),
                    value: -f64::from(value) * 15.0,
                    v120: value.saturating_mul(-120),
                    stop: false,
                    source: 0,
                });
            }
            _ => {} // Keyboard repeats are generated by the Wayland client.
        }
    }
}
struct Device {
    file: File,
    decoder: Decoder,
    relative_samples: u64,
}
pub(crate) struct Input {
    devices: Vec<Device>,
    started: bool,
    relative_supported: bool,
}
impl Input {
    pub(crate) fn open() -> Result<Self> {
        let mut devices = Vec::new();
        if Path::new("/dev/input").is_dir() {
            for entry in fs::read_dir("/dev/input")? {
                let entry = entry?;
                if !entry.file_name().as_encoded_bytes().starts_with(b"event")
                    || !entry.file_type()?.is_char_device()
                {
                    continue;
                }
                let file = OpenOptions::new()
                    .read(true)
                    .custom_flags(libc::O_NONBLOCK)
                    .open(entry.path())
                    .context("open guest virtual input device")?;
                let absolute = axis(&file, 0)?.zip(axis(&file, 1)?).map(|(x, y)| [x, y]);
                let relative_supported = relative_axes(&file)?;
                devices.push(Device {
                    file,
                    relative_samples: 0,
                    decoder: Decoder {
                        absolute,
                        relative_supported,
                        ..Default::default()
                    },
                });
            }
        }
        let relative_supported = devices
            .iter()
            .any(|device| device.decoder.relative_supported);
        Ok(Self {
            devices,
            started: false,
            relative_supported,
        })
    }
    pub(crate) fn relative_supported(&self) -> bool {
        self.relative_supported
    }
    pub(crate) fn diagnostics(&self) -> serde_json::Value {
        serde_json::json!({"devices": self.devices.iter().map(|device|
            serde_json::json!({"relative_supported":device.decoder.relative_supported,
                               "relative_samples":device.relative_samples})
        ).collect::<Vec<_>>()})
    }
    pub(crate) fn poll(&mut self, width: u32, height: u32, now_us: u64) -> Result<Batch> {
        let mut events = Vec::new();
        if !self.started && !self.devices.is_empty() {
            events.extend([
                Event::Focus {
                    keyboard: true,
                    focused: true,
                },
                Event::Focus {
                    keyboard: false,
                    focused: true,
                },
            ]);
            self.started = true;
        }
        for device in &mut self.devices {
            // Linux x86-64 input_event: timeval, u16 type/code, i32 value.
            for _ in 0..64 {
                let mut bytes = [0_u8; 24];
                match device.file.read(&mut bytes) {
                    Ok(0) => anyhow::bail!("virtual input device disconnected"),
                    Ok(size) => {
                        ensure!(size == bytes.len(), "incomplete virtual input event");
                        let kind = u16::from_ne_bytes([bytes[16], bytes[17]]);
                        let code = u16::from_ne_bytes([bytes[18], bytes[19]]);
                        let value =
                            i32::from_ne_bytes([bytes[20], bytes[21], bytes[22], bytes[23]]);
                        if kind == 2 && code <= 1 {
                            device.relative_samples += 1;
                        }
                        device.decoder.event(kind, code, value, &mut events);
                    }
                    Err(error) if error.kind() == io::ErrorKind::WouldBlock => break,
                    Err(error) if error.kind() == io::ErrorKind::Interrupted => continue,
                    Err(error) => return Err(error).context("read guest virtual input"),
                }
            }
        }
        Ok(Batch {
            width,
            height,
            relative_supported: self.relative_supported,
            events: events
                .into_iter()
                .map(|event| TimedEvent {
                    time_us: now_us,
                    event,
                })
                .collect(),
            ..Default::default()
        })
    }
}

